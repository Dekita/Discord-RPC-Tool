const THEME_TEMPLATE = `
/*###################################
*
* ■ Discord RPC Tool by DekitaRPG@gmail.com
* CSS generated by RPC Tool theme customizer
*
*/\n:root {CSS_AREA\n}\n`;

// getting/setting css variables/properties from stylesheet
const STYLES_ELEMENT = document.documentElement;
let randomize_type = null;
// the theme as it was when the customizer opened, restored on discard
let theme_snapshot = null;
let theme_saved = false;

function getVariableFromCSS(propname) {
    const style = getComputedStyle(STYLES_ELEMENT);
    const value = style.getPropertyValue(propname);
    return value?.trim();
}
function setVariableToCSS(propname, value) {
    STYLES_ELEMENT.style.setProperty(propname, value);
}
async function createThemeCssString() {
    const gen_ver = await dekita_rpc.getAppVersion();
    const future_css = [`--dek-gen-version: ${gen_ver};`];
    for (const variable of THEME_VARIABLES) {
        const value = getVariableFromCSS(`--dek-${variable}`);
        if (value) future_css.push(`--dek-${variable}: ${value};`);
    }
    const css_string = future_css.map(string =>`\n\t${string}`).join('');
    const theme_css = THEME_TEMPLATE.replace('CSS_AREA', css_string);
    return theme_css;
}
async function copyCssToClipboard() {
    const theme_css = await createThemeCssString();
    await navigator.clipboard.writeText(theme_css);
    flashButtonIcon(copy_theme_btn, 'fa-check');
    return theme_css;
}
// briefly swaps a buttons icon, eg: to a tick after copying
function flashButtonIcon(button, icon_class) {
    const icon = button.querySelector('i');
    const original = icon.className;
    icon.className = `fas fa-fw ${icon_class}`;
    setTimeout(() => icon.className = original, 1200);
}
async function saveCssToFile() {
    dekita_rpc.saveFileForCSS(await createThemeCssString());
}
async function saveCssToCustom() {
    localStorage.setItem(CUSTOM_THEME_KEY, await createThemeCssString());
    theme_saved = true;
    app_events.emit('custom-theme-saved');
    bootstrap.Modal.getInstance(theme_modal)?.hide();
}
// reads the saved custom theme as {variable: value}, used for its picker tile
export function getCustomThemeColors() {
    const theme_css = localStorage.getItem(CUSTOM_THEME_KEY);
    if (!theme_css) return null;
    return dek_validate.parseThemeVariables(theme_css);
}
// applies the css variables saved by saveCssToCustom
export function loadCustomthemeFromStorage() {
    if (!applyCustomThemeVariables()) return false;
    refreshColorInputs();
    return true;
}

