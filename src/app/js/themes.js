// remembers the current theme so discard can put it back
function takeThemeSnapshot() {
    theme_snapshot = {
        href: areas.head_css_link.getAttribute('href'),
        css: STYLES_ELEMENT.style.cssText,
    };
    theme_saved = false;
    refreshColorInputs();
}
function restoreThemeSnapshot() {
    if (!theme_snapshot) return;
    areas.head_css_link.setAttribute('href', theme_snapshot.href);
    STYLES_ELEMENT.style.cssText = theme_snapshot.css;
    theme_snapshot = null;
}
// swaps the base theme file the customizer is editing on top of
function onPickBaseTheme(theme) {
    STYLES_ELEMENT.style.cssText = '';
    areas.head_css_link.addEventListener('load', refreshColorInputs, {once: true});
    areas.head_css_link.setAttribute('href', `themes/${theme}.css`);
    for (const tile of queryAll('[data-base-theme]')) {
        tile.classList.toggle('selected', tile.dataset.baseTheme === theme);
    }
}

